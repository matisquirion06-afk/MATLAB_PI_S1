function tab = tableauHypotheses(P)
% TABLEAUHYPOTHESES  Tableau des hypothèses, des valeurs estimées et de leurs unités.
%
%   tab = tableauHypotheses(P)    retourne le tableau
%   tableauHypotheses(P)          sans sortie : écrit le tableau à l'écran
%
%   ENTRÉE
%     P     structure des paramètres (voir parametres.m)
%
%   SORTIE
%     tab   tableau de cellules à 6 colonnes. La première ligne contient
%           les titres :
%           Paramètre | Symbole | Valeur | Unité | Source et justification | Statut
%
%   EXIGENCE DE LA CONSIGNE
%     « Les hypothèses, les valeurs estimées et leurs unités doivent être
%     réunies dans un tableau et justifiées. »
%
%   COMMENT ÇA MARCHE
%     Les VALEURS sont lues dans P (elles ne sont donc écrites qu'une
%     seule fois, dans parametres.m). Seuls les textes (description,
%     source, statut) sont écrits ici. Si on change une valeur dans
%     parametres.m, le tableau se met à jour tout seul. Par contre, si on
%     change la SOURCE d'une valeur, il faut corriger le texte ici aussi.
%
%   LÉGENDE : [Fourni] document de l'équipe ; [Web] fiche ou guide de
%   fabricant ; [Claude] hypothèse ou estimation de l'assistant IA.

% Valeurs calculées à partir des paramètres (pour les montrer dans le tableau)
thetaPrise = P.thetaPrise;
thetaDepot = P.thetaDepot;
amplitude = abs(thetaDepot - thetaPrise);
[~, V]  = massePiece(P, 1);
Fvide   = forceMaintien(P);
deg     = 180 / pi;                     % conversion rad -> degrés

% --- Titres des colonnes ---------------------------------------------------------
tab = {'Paramètre', 'Symbole', 'Valeur', 'Unité', 'Source et justification', 'Statut'};

% Chaque instruction ci-dessous ajoute UNE ligne au tableau.
% « tab(end+1, :) = {...} » veut dire : après la dernière ligne, ajouter
% une ligne faite de ces 6 cellules.

% --- Géométrie -------------------------------------------------------------------
tab(end+1, :) = {'Distance pivot - axe de la poulie de ventouse', 'L', ...
    sprintf('%.1f', P.L * 1000), 'mm', ...
    '[Fourni] CAD MPS-12-005 (esquisse « Positions trous », cote D3) ; mesurée dans SolidWorks le 8 nov. 2026', ...
    'Confirmé'};
tab(end+1, :) = {'Hauteur du pivot au-dessus de la table', 'h_pivot', ...
    sprintf('%.1f', P.hPivot * 1000), 'mm', ...
    '[Fourni] Mesurée dans SolidWorks le 8 nov. 2026 (arbre de l''actionneur - dessous du support MPS-12-900)', ...
    'Confirmé (CAD)'};
tab(end+1, :) = {'Distance verticale axe de poulie - lèvre de la ventouse', 'd_levre', ...
    sprintf('%.1f', P.dLevre * 1000), 'mm', ...
    '[Fourni] Mesurée dans SolidWorks (MPS-12-200) le 8 nov. 2026 ; la vidéo montre une ventouse à soufflet plus longue', ...
    'Confirmé (CAD)'};
tab(end+1, :) = {'Hauteur de la surface d''appui à la prise', 'h_prise', ...
    sprintf('%.2f', P.hAppuiPrise * 1000), 'mm', ...
    '[Fourni] Infos visite Cégep.docx, « hauteur du départ » ; table - dessous de la rondelle (précision de Manuel)', ...
    'Provisoire'};
tab(end+1, :) = {'Hauteur de la surface d''appui au dépôt', 'h_depot', ...
    sprintf('%.2f', P.hAppuiDepot * 1000), 'mm', ...
    '[Fourni] Infos visite Cégep.docx, « hauteur de l''arrivée » ; table - dessous de la rondelle (précision de Manuel)', ...
    'Provisoire'};
tab(end+1, :) = {'Angle du bras à la prise (calculé)', 'theta_prise', ...
    sprintf('%.1f', thetaPrise * deg), '°', ...
    '[Claude] Calculé par hauteurAxePoulie.m : sin(phi) = (h_prise + H + d_levre - h_pivot) / L', ...
    'Calculé'};
tab(end+1, :) = {'Angle du bras au dépôt (calculé)', 'theta_depot', ...
    sprintf('%.1f', thetaDepot * deg), '°', ...
    '[Claude] Calculé dans parametres.m ; angle mesuré depuis l''horizontale du côté du dépôt (à droite)', ...
    'Calculé'};
tab(end+1, :) = {'Amplitude de rotation du bras (calculée)', 'delta_theta', ...
    sprintf('%.1f', amplitude * deg), '°', ...
    '[Claude] theta_depot - theta_prise ; à comparer à l''amplitude visible dans la vidéo', ...
    'Calculé'};

% --- Pièce ---------------------------------------------------------------------------
tab(end+1, :) = {'Diamètre de la pièce', 'D', ...
    sprintf('%.1f', P.piece.D * 1000), 'mm', ...
    '[Fourni] Rapport bras rotatif.xlsx, feuille DONNÉES', 'Provisoire'};
tab(end+1, :) = {'Hauteur de la pièce', 'H', ...
    sprintf('%.1f', P.piece.H * 1000), 'mm', ...
    '[Fourni] Rapport bras rotatif.xlsx, feuille DONNÉES', 'Provisoire'};
tab(end+1, :) = {'Volume de la pièce (calculé, constant)', 'V', ...
    sprintf('%.0f', V * 1e9), 'mm^3', ...
    '[Fourni] Formule du tableur (cylindre - trou - cône) ; calculé par massePiece.m', 'Calculé'};

% Une ligne de masse volumique et une ligne de masse par matériau.
% Les sources suivent l'ordre de P.materiaux : Delrin, aluminium, acier.
sourcesRho = { ...
    '[Web] DuPont, fiche technique Delrin 900P : « Density ISO 1183 : 1420 kg/m3 (1.42 g/cm3) »', ...
    '[Web] ASM Material Data Sheet, aluminium 6061-T6 : « Density 2.7 g/cc » ; alliage des rondelles non identifié, valeur typique du 6061', ...
    '[Web] MatWeb, AISI 1020 Steel, cold rolled : « Density 7.87 g/cc » ; nuance demandée par le client ([Fourni] Infos visite Cégep.docx, 24 juin)'};
for i = 1:numel(P.materiaux)
    m = massePiece(P, i);
    if i <= numel(sourcesRho)
        sourceRho = sourcesRho{i};
        statutRho = 'Confirmé (fiche)';
    else
        sourceRho = 'Source à citer';
        statutRho = 'Provisoire';
    end
    tab(end+1, :) = {['Masse volumique - ' P.materiaux(i).nom], 'rho', ...
        sprintf('%.0f', P.materiaux(i).rho), 'kg/m^3', sourceRho, statutRho}; %#ok<AGROW>
    tab(end+1, :) = {['Masse de la pièce - ' P.materiaux(i).nom ' (calculée)'], 'm', ...
        sprintf('%.1f', m * 1000), 'g', ...
        'm = rho x V ; calculée par massePiece.m', 'Calculé'}; %#ok<AGROW>
    tab(end+1, :) = {['Coefficient de frottement ventouse-pièce - ' P.materiaux(i).nom], 'mu', ...
        sprintf('%.2f', P.materiaux(i).mu), '-', ...
        '[Web] Schmalz, « Theoretical Holding Force of a Suction Cup » : 0,5 pour bois, métal, verre, pierre ; essai recommandé', ...
        'Provisoire'}; %#ok<AGROW>
end

% --- Ventouse et vide ------------------------------------------------------------------
tab(end+1, :) = {'Diamètre de la ventouse', 'd_v', ...
    sprintf('%.1f', P.ventouse.diametre * 1000), 'mm', ...
    '[Fourni] CAD SMC-ZP20UN ; décision du 9 nov. 2026 de se fier au CAD (dessin : 30 mm ; notes de visite : environ 38,1 mm)', ...
    'Confirmé (CAD)'};
tab(end+1, :) = {'Niveau de vide', 'delta_p', ...
    sprintf('%.0f', P.vide / 1000), 'kPa', ...
    ['[Fourni] Éjecteur monté : SMC ZU07S (Infos visite Cégep.docx, 24 juin). ' ...
     '[Web] Catalogue SMC série ZU : vide maximal de -85 kPa à 0,45 MPa d''alimentation, sans fuite ' ...
     '(« Vacuum pressure decreases as leakage increases »). [Fourni] Notes de visite : 10 à 12 psi, soit 69 à 83 kPa ' ...
     '(valeur à reconfirmer selon son auteur). Choix de l''équipe : 60 kPa, sous ces deux valeurs, pour rester ' ...
     'prudent face aux fuites ; c''est aussi la valeur de travail des exemples SMC (-60 kPa) et Schmalz (-0,6 bar)'], ...
    'Justifié (choix d''équipe)'};
tab(end+1, :) = {'Force de maintien théorique de la ventouse (calculée)', 'F_vide', ...
    sprintf('%.2f', Fvide), 'N', ...
    '[Web] F = delta_p x aire (Schmalz ; SMC) ; calculée par forceMaintien.m', 'Calculé'};
tab(end+1, :) = {'Facteur de sécurité cible', 'FS_cible', ...
    sprintf('%.2f', P.FScible), '-', ...
    ['Réglage avancé de l''interface (« Marge de sécurité exigée ») ; valeur par défaut : 2,0. ' ...
     '[Web] Schmalz : au moins 1,5 pour des pièces lisses et étanches, 2,0 ou plus pour des pièces critiques. ' ...
     'L''équipe retient 2,0 par défaut : rondelle lisse, mais vide supposé constant et frottement ventouse-pièce ' ...
     'non mesuré (mu = 0,5). Même valeur que le facteur de sécurité du rapport (section 5.2.2)'], ...
    'Justifié (modifiable)'};

% --- Durées du cycle ---------------------------------------------------------------------
tab(end+1, :) = {'Durée totale du cycle', 'T_cycle', ...
    sprintf('%.2f', P.dureeCycle), 's', ...
    '[Fourni] Infos visite Cégep.docx, mandats : « raccourcir le cycle (6 s actuellement) » ; décision d''équipe du 14 nov. 2026', ...
    'Confirmé (client)'};
tab(end+1, :) = {'Durée du transfert avec pièce, mesurée', 'T', ...
    sprintf('%.2f', P.duree.transfert), 's', ...
    sprintf(['[Claude] Vidéo officielle : %g images / %g images par seconde ' ...
             '(moyenne de 26 et 28 images). Rotation comptée directement. ' ...
             'Utilisée en mode « comme la machine actuelle ». En mode « la plus rapide ' ...
             'permise », la durée est un RÉSULTAT des quatre limites (dureeMinimale.m) ; ' ...
             'en mode « je choisis la durée », l''utilisateur la tape'], ...
            P.images.transfert, P.imagesParSeconde), 'Provisoire'};
tab(end+1, :) = {'Durée du retour à vide, mesurée', 't_retour', ...
    sprintf('%.2f', P.duree.retour), 's', ...
    sprintf(['[Claude] Vidéo officielle : %g images / %g images par seconde ' ...
             '(moyenne de 24 et 25 images). Rotation comptée directement. ' ...
             'Utilisée en modes « comme la machine actuelle » et « je choisis la durée ». ' ...
             'En mode « la plus rapide permise », elle découle des limites du vérin ' ...
             'seulement (couple, fréquence, énergie en fin de course), aucune rondelle ' ...
             'n''étant portée'], ...
            P.images.retour, P.imagesParSeconde), 'Provisoire'};
tab(end+1, :) = {'Durée de l''attente à la prise', 't_1', ...
    sprintf('%.2f', P.duree.attentePrise), 's', ...
    sprintf(['[Claude] Reste du cycle de %.1f s après les deux rotations, réparti ' ...
             'selon la proportion observée (%g images contre %g). Les attentes varient ' ...
             'beaucoup d''un cycle à l''autre dans la vidéo : elles dépendent du reste ' ...
             'de la ligne, pas du bras'], P.dureeCycle, P.images.attentePrise, P.images.attenteDepot), ...
    'Provisoire'};
tab(end+1, :) = {'Durée de l''attente au dépôt', 't_3', ...
    sprintf('%.2f', P.duree.attenteDepot), 's', ...
    '[Claude] Reste du cycle, même répartition que l''attente à la prise', ...
    'Provisoire'};

% --- Actionneur et masses en rotation ------------------------------------------------------
tab(end+1, :) = {'Couple théorique de l''actionneur à 6 bar', 'M_act', ...
    sprintf('%.1f', P.actionneur.coupleCatalogue), 'N.m', ...
    ['[Fourni] Catalogue Festo « Semi-rotary drive, metric DSR » (2025/03), p. 4, taille 16. ' ...
     'Valeur par défaut du réglage avancé « Couple du vérin » de l''interface'], 'Confirmé'};
tab(end+1, :) = {'Hypothèse : couple du catalogue appliqué sans correction', '-', '-', '-', ...
    ['[Fourni] Infos visite Cégep.docx (24 juin) : réseau « pneumatique de 6 bar », ' ...
     'pression de référence du catalogue ; mais la même note donne aussi « 60-80 psi » ' ...
     '(4,1 à 5,5 bar), à reconfirmer. [Équipe] Rendement de 100 % (décision du ' ...
     '18 nov. 2026) : aucune donnée de pertes publiée pour le DSR-16 ; Techniques de ' ...
     'l''Ingénieur BM 6 100 – 20, section 6.1.1, donne 3 à 10 % pour les vérins ' ...
     'LINÉAIRES seulement. Couple non modélisé en fonction de la pression : pas de ' ...
     'formule normalisée pour les rotatifs (BM 6 100, section 6.2.1)'], ...
    'Provisoire'};
tab(end+1, :) = {'Durée minimale d''une rotation de l''actionneur', 'T_act', ...
    sprintf('%.3f', P.actionneur.dureeMin), 's', ...
    sprintf(['[Fourni] Fiche Festo DSR, p. 4 : fréquence maximale de %g Hz. La fiche ne dit pas si ce sont ' ...
             'des allers ou des allers-retours. Décision d''équipe (19 nov. 2026) : %g pivotements par seconde, ' ...
             'soit T = 1/f ; c''est l''interprétation prudente (1/(2f) donnerait %.3f s)'], ...
            P.actionneur.frequenceMax, P.actionneur.frequenceMax, 1 / (2 * P.actionneur.frequenceMax)), ...
    'Provisoire (prudent)'};
tab(end+1, :) = {'Énergie admissible en fin de course, sans butées externes', 'E_max', ...
    sprintf('%.4f', P.actionneur.festo.energieMax), 'J', ...
    ['[Fourni] Fiche Festo DSR, p. 5, graphique J en fonction du temps de pivotement (DSR-16, courbe 180°). ' ...
     '[Claude] Les 6 points lus donnent tous E = 1/2 J (pi/t)^2 = 0,010 à 0,011 J (moyenne retenue) ; ' ...
     'les courbes à 90° et 120° donnent la même énergie (test F2)'], ...
    'Provisoire (lecture de graphique)'};
tab(end+1, :) = {'Hypothèse : limite Festo appliquée à 165,5° avec la vitesse moyenne', '-', '-', '-', ...
    ['[Claude] T_festo = Dtheta * racine(J / (2 Emax)). Le vérin réel frappe ses tampons : on prend la vitesse ' ...
     'moyenne comme Festo, pas la vitesse nulle de la loi cubique. Au-delà de J = ' ...
     sprintf('%.0fe-4', P.actionneur.festo.Jgraphique * 1e4) ' kg.m^2 (haut du graphique), la durée est une ' ...
     'EXTRAPOLATION : c''est le cas de tous les cas de charge du bras. Sans butées externes ([Fourni] notes de ' ...
     'visite : « Pas d''amortisseurs »), la limite est une contrainte stricte'], ...
    'Provisoire (extrapolation)'};
tab(end+1, :) = {'Masse du bras et du pont', 'm_bras', ...
    sprintf('%.4f', P.bras.masse), 'kg', ...
    '[Fourni] SolidWorks, Propriétés de masse (19 nov. 2026) : MPS-12-002 = 0,278 lb, MPS-12-005 = 0,402 lb', ...
    'Confirmé (CAD)'};
tab(end+1, :) = {'Distance pivot - centre de masse du bras', 'd_CM', ...
    sprintf('%.1f', P.bras.distCM * 1000), 'mm', ...
    ['[Fourni] SolidWorks, outil Mesurer entre le Centre de masse et l''axe du pivot : 3,428 po (MPS-12-002) ' ...
     'et 3,492 po (MPS-12-005) ; moyenne pondérée par les masses'], ...
    'Confirmé (CAD)'};
tab(end+1, :) = {'Moment d''inertie du bras autour du pivot', 'J_bras', ...
    sprintf('%.4e', P.bras.Jpivot), 'kg.m^2', ...
    ['[Fourni] SolidWorks : Lyy au centre de gravité = 1,704 et 1,851 lb.po^2 ; ' ...
     '[Claude] théorème des axes parallèles, J = somme(Lyy + m*d^2). ' ...
     'L''ancien modèle de barre uniforme donnait un J 1,2 % plus grand (test C6)'], ...
    'Confirmé (CAD)'};
tab(end+1, :) = {'Masse de l''ensemble ventouse', 'm_v', ...
    sprintf('%.3f', P.masseVentouse), 'kg', ...
    '[Fourni] CAD, propriété « Mass » de l''assemblage MPS-12-200', 'Confirmé (CAD)'};
tab(end+1, :) = {'Accélération gravitationnelle', 'g', ...
    sprintf('%.2f', P.g), 'm/s^2', 'Valeur usuelle', 'Confirmé'};

% --- Hypothèses de modélisation (sans valeur numérique) --------------------------------------
tab(end+1, :) = {'Hypothèse : la pièce ne tourne pas sur elle-même', '-', '-', '-', ...
    '[Fourni] Courroie crantée et deux poulies de 22 dents (CAD MPS-12-006 et MPS-12-007) ; consigne, section 5.4', ...
    'Confirmé (CAD)'};
tab(end+1, :) = {'Hypothèse : le bras suit une loi de mouvement analytique', '-', '-', '-', ...
    '[Fourni] Imposé par la consigne ; loi cubique : Craig, chap. 7. Seule loi tirée d''une source que l''équipe maîtrise. Accélération discontinue aux deux bouts', ...
    'Confirmé (cubique)'};
tab(end+1, :) = {'Hypothèse : la pièce est portée par la ventouse seulement pendant le transfert', '-', '-', '-', ...
    '[Claude] Aux attentes, la pièce repose sur son support', 'Provisoire'};
tab(end+1, :) = {'Hypothèse : le niveau de vide est constant pendant le transfert', '-', '-', '-', ...
    '[Claude] Fuites et temps d''établissement du vide négligés', 'Provisoire'};
tab(end+1, :) = {'Hypothèse : force de maintien requise = F_y + |F_x| / mu', '-', '-', '-', ...
    '[Web] Combinaison des cas de charge I et II de Schmalz ; voir effortVentouse.m', 'Provisoire'};
% [Claude] Lignes ajoutées le 19 nov. 2026 après la relecture du code :
% hypothèses déjà appliquées par les fonctions, mais absentes du tableau.
tab(end+1, :) = {'Hypothèse : mouvement plan, bras rigide', '-', '-', '-', ...
    '[Claude] Le bras tourne dans un plan vertical et ne fléchit pas ; aucune vibration (cinematiquePiece.m, momentPivot.m)', ...
    'Provisoire'};
tab(end+1, :) = {'Hypothèse : ensemble ventouse compté comme une masse au bout du bras', '-', '-', '-', ...
    ['[Claude] I_ven = (m_v + m) L^2 : la courroie garde l''ensemble vertical, il se déplace sans tourner sur ' ...
     'lui-même (momentPivot.m). Courroie supposée inextensible'], ...
    'Provisoire'};
tab(end+1, :) = {'Hypothèse : frottement au pivot et inertie interne du vérin négligés', '-', '-', '-', ...
    ['[Claude] Le couple sert seulement à accélérer le bras et à vaincre la gravité. La palette et l''arbre du ' ...
     'DSR-16 ne sont pas comptés (aucune valeur publiée)'], ...
    'Provisoire'};
tab(end+1, :) = {'Hypothèse : couple du vérin constant sur toute la course', '-', '-', '-', ...
    '[Claude] 2 N.m disponibles à tout angle et à toute vitesse ; pas de modèle de pression ni de débit', ...
    'Provisoire'};
tab(end+1, :) = {'Hypothèse : retour à vide limité par le vérin seulement', '-', '-', '-', ...
    '[Claude] Sans rondelle, aucun critère de ventouse : couple, fréquence et énergie en fin de course', ...
    'Provisoire'};
tab(end+1, :) = {'Hypothèse : durées calculées arrondies au millième supérieur', '-', '-', '-', ...
    ['[Claude] ceil(T x 1000) / 1000 : le FS obtenu est un peu plus grand que la cible et le couple requis ' ...
     'un peu plus petit, jamais l''inverse (RED_IUG.m)'], ...
    'Calculé'};

% --- Écriture à l'écran si aucune sortie n'est demandée ---------------------------------------
% nargout est le nombre de sorties demandées par celui qui appelle la fonction.
if nargout == 0
    fprintf('\nTABLEAU DES HYPOTHÈSES, DES VALEURS ESTIMÉES ET DES UNITÉS\n\n');
    for i = 1:size(tab, 1)
        fprintf('%-62s | %-12s | %9s | %-7s | %-26s | %s\n', ...
                tab{i, 1}, tab{i, 2}, tab{i, 3}, tab{i, 4}, tab{i, 6}, tab{i, 5});
    end
    fprintf('\n');
    clear tab;              % évite que Matlab réaffiche le tableau brut
end

end
